public class desafio14 {
    public static void main(String[] args) {
        double celsius = 28.0;
        double fahrenheit = (celsius * 9 / 5) + 32;

        System.out.println("A temperatura em Fahrenheit é: " +
        fahrenheit);
    }

}

// formula Fahrenheit = (Celsius * 9/5) + 32